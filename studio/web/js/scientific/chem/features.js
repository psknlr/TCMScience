function bondTypeName(json, i, bo) {
  if (bo === 0) {
    const q = (json.molecules[0].extensions || []).find((e) => e.name === "rdkitQueries")?.bondQueries?.[i];
    return q?.descr === "BondNull" ? "UNSPECIFIED" : "ZERO";
  }
  return BOND_TYPE_NAMES[bo] || `bond order ${bo}`;
}

/** Refuses a molecule with a bond the ports do not take, naming the first such type alphabetically. */
function checkBondTypes(mol) {
  const json = molJson(mol);
  const dB = json.defaults.bond;
  const odd = new Set();
  (json.molecules[0].bonds || []).forEach((b, i) => {
    const bo = b.bo ?? dB.bo;
    if (bo !== 1 && bo !== 2 && bo !== 3) odd.add(bondTypeName(json, i, bo));
  });
  if (odd.size) {
    const type = [...odd].sort()[0];
    throw refusal(`feature ports: bond type ${type}`, `the feature ports take single, double, triple and aromatic bonds; ` +
      `this molecule has a ${type} bond (native RDKit on the runner computes its features)`);
  }
}

/**
 * The features of one standardised molecule → {row: Float32Array(2073) (featurize's row), bits: Uint8Array(256)
 * (bits(), MSB first), descriptors: {24 + FormalCharge: float64, NaN where chem.descriptors gives NaN}, atomsWithH
 * (Chem.AddHs(mol).GetNumAtoms())}. Throws ChemError "refused" for a molecule a port cannot take, or when the count
 * port's bits are not RDKit.js's.
 */
export function features(ctx, mol, tables) {
  checkBondTypes(mol);
  const g = graph(ctx, mol);
  const d = JSON.parse(mol.get_descriptors());
  const desc = {};
  for (const k of DESCRIPTORS) if (k in DIRECT) desc[k] = d[DIRECT[k]];
  desc.FormalCharge = g.atoms.reduce((s, a) => s + a.chg, 0);
  const H = g.hNoNbr();
  let valence = 0;
  g.atoms.forEach((a, i) => { valence += tables.periodic[a.z].nOuter - a.chg + H[i]; });
  desc.NumValenceElectrons = valence;
  const dm = distanceMatrix(g);
  desc.BalabanJ = balabanJ(g, dm);
  desc.BertzCT = bertzCT(g, dm);
  desc.qed = qed(g, d, ctx, mol, tables);
  const charges = gasteiger(g, tables);
  desc.MaxPartialCharge = charges.max;
  desc.MinPartialCharge = charges.min;
  for (const k of FEATURE_KEYS) {
    const v = desc[k];
    if (typeof v !== "number") throw refusal(`descriptor ${k}`, `RDKit.js gave no ${k} for this molecule`);
    if (!Number.isFinite(v)) desc[k] = NaN; // chem.descriptors: non-finite -> NaN
  }

  const lsb = mol.get_morgan_fp_as_uint8array(MORGAN);
  const counts = morganCounts(g, tables);
  for (let i = 0; i < FP_BITS; i++) {
    if (Boolean(counts[i]) !== Boolean(lsb[i >> 3] & (1 << (i & 7)))) {
      throw refusal("Morgan count fingerprint port", `the Morgan count port disagrees with RDKit.js's bit vector at bit ${i}; ` +
        "the counts are not used");
    }
  }
  const row = new Float32Array(N_FEATURES);
  for (let i = 0; i < FP_BITS; i++) row[i] = Math.min(counts[i], 255);
  FEATURE_KEYS.forEach((k, j) => { const v = desc[k]; row[FP_BITS + j] = Number.isFinite(v) ? v : 0; });
  return { row, bits: packBitsMsbFirst(lsb), descriptors: desc, atomsWithH: d.NumAtoms };
}

