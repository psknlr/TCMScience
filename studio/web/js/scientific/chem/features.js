/** The data features() needs from rdkit_tables.json (generated by studio/scripts/make_chem_fixtures.py). */
export class FeatureTables {
  constructor(doc) {
    if (doc?.schema !== "tcmstudio.rdkit-tables/1") throw new TypeError("not a tcmstudio.rdkit-tables/1 document");
    this.release = doc.rdkit;
    this.periodic = doc.periodic.map((p) => Object.freeze({
      symbol: p.symbol, weight: p.weight, nOuter: p.n_outer, defaultValence: p.default_valence,
      valenceList: p.valence_list, isotopes: p.isotopes,
    }));
    this.qed = doc.qed;
    this.gasteiger = new Map();
    for (const [elem, mode, a, b, c] of doc.gasteiger) this.gasteiger.set(`${elem}|${mode}`, [a, b, c]); // a later line wins
  }

  /** Atom::getMass(): an isotope's mass from the table, its mass number when RDKit has no mass for it (not for Z=0),
   * else the element's weight. */
  mass(z, isotope) {
    const p = this.periodic[z];
    if (!isotope) return p.weight;
    const m = p.isotopes[String(isotope)];
    if (m !== undefined) return m;
    return z !== 0 ? isotope : 0;
  }
}

// ---- Morgan count fingerprint, radius 2 (MorganGenerator.cpp, FingerprintUtil.cpp getConnectivityInvariants) ------

// gboost::hash_combine on std::uint32_t (Code/RDGeneral/hash/hash.hpp)
function hashCombine(seed, v) {
  return (seed ^ (((v >>> 0) + 0x9e3779b9 + ((seed << 6) >>> 0) + (seed >>> 2)) >>> 0)) >>> 0;
}
function hashRange(values) {
  let s = 0;
  for (const v of values) s = hashCombine(s, v);
  return s;
}
const hashPair = (a, b) => hashCombine(hashCombine(0, a), b);

/** Every environment's hash, as MorganEnvironmentGenerator yields them (radius 0 first, duplicate neighbourhoods
 * dropped as RDKit drops them). */
export function morganEnvironments(g, tables, radius = 2) {
  const { n, atoms, bonds, nbrBonds, inRing } = g;
  const H = g.hNoNbr();
  const inv = new Uint32Array(n);
  for (let i = 0; i < n; i++) {
    const a = atoms[i];
    let hNbr = 0;
    for (const bi of nbrBonds[i]) if (atoms[other(bonds[bi], i)].z === 1) hNbr++;
    const deltaMass = Math.trunc(tables.mass(a.z, a.isotope) - tables.periodic[a.z].weight);
    const parts = [a.z, nbrBonds[i].length + H[i], H[i] + hNbr, a.chg, deltaMass];
    if (inRing[i]) parts.push(1);
    inv[i] = hashRange(parts);
  }
  const envs = Array.from(inv);
  let cur = Array.from(inv);
  let atomNbhd = Array.from({ length: n }, () => 0n);
  const roundNbhd = Array.from({ length: n }, () => 0n);
  const dead = new Uint8Array(n);
  const seen = new Set();
  for (let layer = 0; layer < radius; layer++) {
    const all = [];
    const next = new Array(n).fill(0);
    for (let i = 0; i < n; i++) {
      if (dead[i]) continue;
      if (!nbrBonds[i].length) {
        dead[i] = 1;
        continue;
      }
      const nb = [];
      for (const bi of nbrBonds[i]) {
        roundNbhd[i] |= 1n << BigInt(bi);
        const o = other(bonds[bi], i);
        roundNbhd[i] |= atomNbhd[o];
        nb.push([bonds[bi].type, cur[o]]);
      }
      nb.sort((x, y) => (x[0] - y[0]) || (x[1] - y[1]));
      let v = hashCombine(layer >>> 0, cur[i]);
      for (const [bt, ci] of nb) v = hashCombine(v, hashPair(bt, ci));
      next[i] = v;
      all.push([roundNbhd[i], v, i]);
    }
    all.sort((x, y) => (x[0] < y[0] ? -1 : x[0] > y[0] ? 1 : (x[1] - y[1]) || (x[2] - y[2])));
    for (const [nbhd, v, i] of all) {
      if (!seen.has(nbhd)) {
        envs.push(v);
        seen.add(nbhd);
      } else {
        dead[i] = 1;
      }
    }
    cur = next;
    atomNbhd = roundNbhd.slice();
  }
  return envs;
}

/** GetCountFingerprintAsNumPy (raw counts) → Uint32Array(2048). */
export function morganCounts(g, tables) {
  const c = new Uint32Array(FP_BITS);
  for (const v of morganEnvironments(g, tables)) c[v % FP_BITS]++;
  return c;
}

/** RDKit.js's Morgan bit vector (LSB first in each byte) → np.packbits's MSB-first bytes. */
export function packBitsMsbFirst(lsbFirst) {
  const out = new Uint8Array(lsbFirst.length);
  for (let k = 0; k < lsbFirst.length; k++) {
    let x = lsbFirst[k];
    let r = 0;
    for (let b = 0; b < 8; b++) {
      r = (r << 1) | (x & 1);
      x >>= 1;
    }
    out[k] = r;
  }
  return out;
}

// ---- distance matrix with bond orders (MolOps::getDistanceMat, useBO, Matrices.cpp FloydWarshall) -----------------
function distanceMatrix(g) {
  const n = g.n;
  let last = new Float64Array(n * n).fill(1e8);
  for (let i = 0; i < n; i++) last[i * n + i] = 0;
  for (const b of g.bonds) {
    const c = b.arom ? 2 / 3 : 1 / bondTypeAsDouble(b.type);
    last[b.a * n + b.b] = c;
    last[b.b * n + b.a] = c;
  }
  let curr = new Float64Array(n * n);
  for (let k = 0; k < n; k++) {
    const kt = k * n;
    for (let i = 0; i < n; i++) {
      const it = i * n;
      for (let jj = 0; jj < n; jj++) {
        const v1 = last[it + jj];
        const v2 = last[it + k] + last[kt + jj];
        curr[it + jj] = v1 <= v2 ? v1 : v2;
      }
    }
    const t = curr;
    curr = last;
    last = t;
  }
  return last;
}

// GraphDescriptors.BalabanJ (rdkit/Chem/GraphDescriptors.py); on a molecule with no atoms it raises (the distance
// matrix it gets is 0, not a matrix), which chem.descriptors turns into NaN
function balabanJ(g, d) {
  const n = g.n;
  if (n === 0) return NaN;
  const q = g.bonds.length;
  const s = new Float64Array(n);
  for (let i = 0; i < n; i++) for (let j = 0; j < n; j++) s[j] += d[i * n + j];
  const adj = new Uint8Array(n * n);
  for (const b of g.bonds) {
    adj[b.a * n + b.b] = 1;
    adj[b.b * n + b.a] = 1;
  }
  const mu = q - n + 1;
  let sum = 0;
  for (let i = 0; i < n; i++) {
    const si = s[i];
    for (let j = i; j < n; j++) if (adj[i * n + j] === 1) sum += 1 / Math.sqrt(si * s[j]);
  }
  return mu + 1 !== 0 ? q / (mu + 1) * sum : 0;
}

// InfoEntropy (Code/ML/InfoTheory/InfoGainFuncs.h), the double instantiation rdkit.ML.InfoTheory calls
function infoEntropy(arr) {
  let total = 0;
  for (const x of arr) total += x;
  let acc = 0;
  if (total !== 0) {
    for (const x of arr) {
      const d = x / total;
      if (d !== 0) acc += -d * Math.log(d);
    }
  }
  return acc / Math.log(2.0);
}

// Python's '%.4f'
function fmt4(x) {
  if (x === Infinity) return "inf";
  if (Number.isNaN(x)) return "nan";
  return x.toFixed(4);
}

// GraphDescriptors.BertzCT (cutoff=100, forceDMat=1)
function bertzCT(g, bd) {
  const n = g.n;
  const cutoff = 100;
  if (n < 2) return 0;
  const bondDict = new Map();
  const nList = new Array(n).fill(null);
  for (const b of g.bonds) {
    let a1 = b.a;
    let a2 = b.b;
    if (a1 > a2) [a1, a2] = [a2, a1];
    bondDict.set(a1 * n + a2, b.arom ? 1.5 : bondTypeAsDouble(b.type));
    if (nList[a1] === null) nList[a1] = [a2];
    else if (!nList[a1].includes(a2)) nList[a1].push(a2);
    if (nList[a2] === null) nList[a2] = [a1];
    else if (!nList[a2].includes(a1)) nList[a2].push(a1);
  }
  const degree = nList.map((l) => (l ? (l.sort((x, y) => x - y), l.length) : 0));
  const keys = new Map();
  const symmetry = new Array(n);
  for (let i = 0; i < n; i++) {
    const row = Float64Array.from(bd.subarray(i * n, i * n + n)).sort().subarray(0, cutoff);
    let key = "";
    for (const x of row) key += fmt4(x) + ",";
    if (!keys.has(key)) keys.set(key, keys.size);
    symmetry[i] = keys.get(key) + 1;
  }
  const look = (x, y) => bondDict.get(x < y ? x * n + y : y * n + x);
  const atomTypes = new Map();
  const connections = new Map();
  const add = (m, k, v) => m.set(k, (m.has(k) ? m.get(k) : 0) + v);
  for (let a = 0; a < n; a++) {
    add(atomTypes, g.atoms[a].z, 1);
    const hc = symmetry[a];
    const nn = degree[a];
    for (let i = 0; i < nn; i++) {
      const ni = nList[a][i];
      const niC = symmetry[ni];
      const bi = look(a, ni);
      if (bi > 1 && ni > a) add(connections, `${Math.min(hc, niC)},${Math.max(hc, niC)}`, bi * (bi - 1) / 2);
      for (let j = i + 1; j < nn; j++) {
        const nj = nList[a][j];
        const njC = symmetry[nj];
        const bj = look(a, nj);
        add(connections, `${Math.min(niC, njC)},${hc},${Math.max(niC, njC)}`, bi * bj);
      }
    }
  }
  if (!connections.size) connections.set("a", 1);
  const cl = [...connections.values()];
  let tot = 0;
  for (const x of cl) tot += x;
  const connIE = tot * (infoEntropy(cl) + Math.log(tot) / Math.log(2));
  const atomIE = n * infoEntropy([...atomTypes.values()]);
  return atomIE + connIE;
}

// ---- QED 1.1.0 (rdkit/Chem/QED.py) -------------------------------------------------------------------------------
// len(Chem.GetSSSR(Chem.DeleteSubstructs(mol, AliphaticRings))): the cycle rank E - V + C of what remains
function cycleRankAfterDelete(g, deleted) {
  const keep = [];
  for (let i = 0; i < g.n; i++) if (!deleted.has(i)) keep.push(i);
  const parent = new Map(keep.map((i) => [i, i]));
  const find = (x) => {
    while (parent.get(x) !== x) {
      parent.set(x, parent.get(parent.get(x)));
      x = parent.get(x);
    }
    return x;
  };
  let edges = 0;
  for (const b of g.bonds) {
    if (deleted.has(b.a) || deleted.has(b.b)) continue;
    edges++;
    const ra = find(b.a);
    const rb = find(b.b);
    if (ra !== rb) parent.set(ra, rb);
  }
  return edges - keep.length + new Set(keep.map(find)).size;
}

function ads(x, p) {
  const exp1 = 1 + Math.exp(-1 * (x - p.C + p.D / 2) / p.E);
  const exp2 = 1 + Math.exp(-1 * (x - p.C - p.D / 2) / p.F);
  const dx = p.A + p.B / exp1 * (1 - 1 / exp2);
  return dx / p.DMAX;
}

// QED.properties: Strict rotatable bonds, which RDKit's default NumRotatableBonds option resolves to
function qed(g, d, ctx, mol, tables) {
  const T = tables.qed;
  let hba = 0;
  for (const s of T.acceptors) hba += ctx.matches(mol, s).length;
  let alerts = 0;
  for (const s of T.alerts) if (ctx.hasMatch(mol, s)) alerts++;
  const arom = cycleRankAfterDelete(g, new Set(ctx.firstAtoms(mol, T.aliphatic_rings)));
  const props = { MW: d.amw, ALOGP: d.CrippenClogP, HBA: hba, HBD: d.NumHBD, PSA: d.tpsa, ROTB: d.NumRotatableBonds,
    AROM: arom, ALERTS: alerts };
  let t = 0;
  T.properties.forEach((k, i) => { t += T.weight_mean[i] * Math.log(ads(props[k], T.ads[k])); });
  let sw = 0;
  for (const w of T.weight_mean) sw += w;
  return Math.exp(t / sw);
}

// ---- Gasteiger charges (PartialCharges/GasteigerCharges.cpp; parameters GasteigerParams.cpp via rdkit_tables) ------
const IONXH = 20.02;
const DAMP = 0.5;
const DAMP_SCALE = 0.5;
const EPS_DOUBLE = Number.EPSILON;

function gasteigerParams(tables, elem, mode) {
  return tables.gasteiger.get(`${elem}|${mode}`) || tables.gasteiger.get("X|*");
}

// MolOps::setConjugation (ConjugHybrid.cpp), with countAtomElec (Aromaticity.cpp)
function conjugation(g, tables) {
  const { n, atoms, bonds, nbrBonds } = g;
  const H = g.hNoNbr();
  const V = g.totalValence();
  const PT = tables.periodic;
  const countAtomElec = (i) => {
    const a = atoms[i];
    const dv = PT[a.z].defaultValence;
    if (dv <= 1) return -1;
    let degree = nbrBonds[i].length + H[i];
    for (const bi of nbrBonds[i]) if (!bondTypeAsDouble(bonds[bi].type)) degree--;
    if (degree > 3) return -1;
    const nlp = Math.max(PT[a.z].nOuter - dv - a.chg, 0);
    return (dv - degree) + nlp - a.nRad; // RDKit then caps a result > 1 at 1, which cannot change its sign
  };
  const candidate = new Uint8Array(n);
  const nSubstituents = new Int32Array(n);
  for (let i = 0; i < n; i++) {
    const a = atoms[i];
    const valences = PT[a.z].valenceList;
    const totalDegree = nbrBonds[i].length + H[i];
    let c;
    if (!a.chg && valences[0] >= 0 && V[i] > valences[0]) {
      c = false;
    } else {
      const no = PT[a.z].nOuter;
      c = ((a.z <= 10) || (no !== 5 && no !== 6) || (no === 6 && totalDegree < 2)) && countAtomElec(i) > 0;
    }
    candidate[i] = c ? 1 : 0;
    nSubstituents[i] = c ? totalDegree : 0;
  }
  const conj = bonds.map((b) => b.arom);
  for (let i = 0; i < n; i++) {
    if (!candidate[i] || nSubstituents[i] < 2 || nSubstituents[i] > 3) continue;
    for (const b1 of nbrBonds[i]) {
      if (bondTypeAsDouble(bonds[b1].type) < 1.5 || !candidate[other(bonds[b1], i)]) continue;
      for (const b2 of nbrBonds[i]) {
        if (b1 === b2) continue;
        const a2 = other(bonds[b2], i);
        if (nSubstituents[a2] > 3) continue;
        if (candidate[a2]) {
          conj[b1] = true;
          conj[b2] = true;
        }
      }
    }
  }
  return conj;
}

/** ComputeGasteigerCharges (12 iterations) → Descriptors._ChargeDescriptors' (min, max), with Python's min()/max()
 * argument order, which decides what a NaN charge gives. */
function gasteiger(g, tables) {
  const { n, atoms, bonds, nbrBonds } = g;
  for (const b of bonds) bondTypeAsDouble(b.type);
  const H = g.hNoNbr();
  const hyb = g.hyb();
  const PT = tables.periodic;
  const charges = new Float64Array(n);
  if (atoms.some((a) => a.chg)) { // splitChargeConjugated
    const conj = conjugation(g, tables);
    for (let ai = 0; ai < n; ai++) {
      let formal = atoms[ai].chg;
      const marker = [];
      if (Math.abs(formal) > EPS_DOUBLE && Math.abs(charges[ai]) < EPS_DOUBLE) {
        marker.push(ai);
        for (const b1 of nbrBonds[ai]) {
          if (!conj[b1]) continue;
          const aax = other(bonds[b1], ai);
          for (const b2 of nbrBonds[aax]) {
            if (b1 === b2 || !conj[b2]) continue;
            const yax = other(bonds[b2], aax);
            if (atoms[ai].z === atoms[yax].z) {
              formal += atoms[yax].chg;
              marker.push(yax);
            }
          }
        }
        for (const mci of marker) charges[mci] = formal / marker.length;
      }
    }
  }
  const params = [];
  const ionX = new Float64Array(n);
  for (let i = 0; i < n; i++) {
    const a = atoms[i];
    let mode = "";
    if (hyb[i] !== "other") mode = hyb[i];
    else if (a.z === 1) mode = "*";
    else if (a.z === 16) {
      let oxygens = 0;
      for (const bi of nbrBonds[i]) if (atoms[other(bonds[bi], i)].z === 8) oxygens++;
      mode = oxygens === 2 ? "so2" : oxygens === 1 ? "so" : "sp3";
    }
    const p = gasteigerParams(tables, PT[a.z].symbol, mode);
    params.push(p);
    ionX[i] = a.z === 1 ? IONXH : p[0] + p[1] + p[2];
  }
  const hP = gasteigerParams(tables, "H", "*");
  const hCharge = new Float64Array(n);
  const energ = new Float64Array(n);
  let damp = DAMP;
  for (let itx = 0; itx < 12; itx++) {
    for (let i = 0; i < n; i++) energ[i] = params[i][0] + charges[i] * (params[i][1] + params[i][2] * charges[i]);
    for (let i = 0; i < n; i++) {
      let dq = 0;
      for (const bi of nbrBonds[i]) {
        const nb = other(bonds[bi], i);
        const dx = energ[nb] - energ[i];
        const sgn = dx < 0 ? 0 : 1;
        dq += dx / ((sgn * (ionX[i] - ionX[nb])) + ionX[nb]);
      }
      const hs = H[i];
      if (hs > 0) {
        const qHs = hCharge[i] / hs;
        const enr = hP[0] + qHs * (hP[1] + hP[2] * qHs);
        const dx = enr - energ[i];
        const sgn = dx < 0 ? 0 : 1;
        const dqH = dx / ((sgn * (ionX[i] - IONXH)) + IONXH);
        dq += (hs * dqH);
        hCharge[i] -= (hs * dqH * damp);
      }
      charges[i] += (damp * dq);
    }
    damp *= DAMP_SCALE;
  }
  let min = 500;
  let max = -500;
  for (let i = 0; i < n; i++) {
    const c = charges[i];
    min = (min < c) ? min : c;
    max = (max > c) ? max : c;
  }
  return { min, max };
}

