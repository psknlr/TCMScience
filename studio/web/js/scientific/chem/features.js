// The ADMET feature row of bioagent.admet.chem in the browser: featurize()'s 2073 float32 columns (the 2048-bit Morgan
// count fingerprint, radius 2, counts clipped at 255, then the 24 descriptors and FormalCharge, NaN and ±inf as 0),
// bits()'s packed Morgan bits for the applicability domain, and the float64 descriptors rules.py reads.
//
// What RDKit.js computes itself is taken as it is: 18 descriptors from get_descriptors() (the same C++ functions as
// rdkit.Chem.Descriptors), the Morgan bit vector and the atom count with hydrogens. The rest is ported from RDKit
// 2026.09.1, each port citing its source, and reads RDKit's own perception through molecule.js: the Morgan count
// fingerprint (MinimalLib has none), FormalCharge, NumValenceElectrons, BalabanJ, BertzCT, qed and Gasteiger's
// Max/MinPartialCharge. The count port checks itself against RDKit.js's bit vector on every molecule. Against native
// RDKit on the parity corpus (web/test/fixtures/chem_parity.json) the float32 row is identical for every molecule;
// in float64, BertzCT and qed can differ in the last bit, because V8's Math.exp and Math.log are not glibc's.
//
// A molecule a port cannot take (a dative, zero-order or unspecified bond, a perception value RDKit.js does not give)
// is refused (ChemError "refused"), never given a guessed value.

