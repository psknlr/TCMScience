const DICTS = { zh: ZH, en: EN };
const KEY = "tcmstudio.admin.lang";

function initial() {
  try {
    const q = new URLSearchParams(location.search).get("lang");
    if (q === "zh" || q === "en") return q;
    const saved = localStorage.getItem(KEY);
    if (saved === "zh" || saved === "en") return saved;
  } catch { /* storage blocked */ }
  return /^zh\b/i.test(navigator.language || "zh") ? "zh" : "en";
}

let current = initial();

export const lang = () => current;

export function setLang(l) {
  current = l === "en" ? "en" : "zh";
  try { localStorage.setItem(KEY, current); } catch { /* storage blocked */ }
  document.documentElement.lang = current === "zh" ? "zh-Hans" : "en";
}

/** The word for `key` ("kinds.scanner" reaches into a group), with {name} filled from vars. */
export function t(key, vars = {}) {
  const dict = DICTS[current];
  let v = key.split(".").reduce((o, k) => (o && typeof o === "object" ? o[k] : undefined), dict);
  if (typeof v !== "string") v = key.split(".").reduce((o, k) => (o && typeof o === "object" ? o[k] : undefined), ZH);
  if (typeof v !== "string") return key.split(".").at(-1);
  return v.replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined || vars[k] === null ? m : String(vars[k])));
}

export { ZH, EN };
